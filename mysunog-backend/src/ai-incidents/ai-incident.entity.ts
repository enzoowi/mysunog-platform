import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
} from 'typeorm';
import {
  AiIncidentStatus,
  IncidentPriority,
  FireGrowthStatus,
  AiDetectionType,
} from './enums';

/**
 * AiIncident — Core entity for AI-detected fire/smoke incidents.
 *
 * Design notes:
 * - UUID primary key for clean REST URLs (/ai/incidents/:uuid)
 * - Stores BOTH the raw AI prediction data AND the human verification result
 *   in clearly separated column groups so the thesis distinction
 *   "AI PREDICTION ≠ HUMAN CONFIRMATION" is enforced at the DB level.
 * - `severityReasons` (JSONB array) stores the interpretable explanations
 *   generated by the SeverityEngine — this is the "explainability" feature.
 * - `areaHistory` (JSONB array) stores the fire area % time series for
 *   displaying growth charts on the BFP dashboard.
 * - Indexed on: status, priority, cameraId, createdAt for fast dashboard queries.
 */
@Entity('ai_incidents')
@Index(['status'])
@Index(['priority'])
@Index(['cameraId'])
@Index(['createdAt'])
export class AiIncident {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  // ── AI Detection Data (set by the AI service, never modified by humans) ──

  @Column({
    type: 'enum',
    enum: AiDetectionType,
    default: AiDetectionType.FIRE,
  })
  detectionType: AiDetectionType;

  /** Highest YOLO confidence score in the triggering frame (0.0–1.0) */
  @Column('decimal', { precision: 5, scale: 4 })
  detectionConfidence: number;

  // ── Camera / Source Information ──────────────────────────────────────────

  /** The camera_id string from the AI service (e.g. "webcam", "cam-01") */
  @Column()
  cameraId: string;

  /** Human-readable camera name (from camera registry or connect request) */
  @Column({ nullable: true })
  cameraName: string;

  /** Physical location description */
  @Column({ nullable: true })
  cameraLocation: string;

  /** URL of the captured frame */
  @Column({ nullable: true })
  imageUrl: string;

  @Column('decimal', { precision: 10, scale: 7, nullable: true })
  latitude: number;

  @Column('decimal', { precision: 10, scale: 7, nullable: true })
  longitude: number;

  // ── Temporal Analysis ────────────────────────────────────────────────────

  @Column({ type: 'timestamp' })
  firstDetectionTime: Date;

  @Column({ type: 'timestamp', nullable: true })
  lastDetectionTime: Date;

  /** Total seconds the AI has been continuously detecting this event */
  @Column('decimal', { precision: 8, scale: 2, default: 0 })
  durationSeconds: number;

  /** Number of consecutive confirmed-detection frames */
  @Column({ default: 0 })
  consecutiveFrameCount: number;

  @Column({
    type: 'enum',
    enum: FireGrowthStatus,
    default: FireGrowthStatus.UNKNOWN,
  })
  growthStatus: FireGrowthStatus;

  /**
   * Chronological array of fire area % readings (one per analyzed frame).
   * Used to render growth charts on the dashboard.
   * Example: [10.2, 12.5, 18.1, 25.0]
   */
  @Column('jsonb', { nullable: true, default: [] })
  fireAreaHistory: number[];

  /**
   * Chronological array of smoke area % readings.
   */
  @Column('jsonb', { nullable: true, default: [] })
  smokeAreaHistory: number[];

  // ── Severity Assessment ──────────────────────────────────────────────────

  /** 0–100 composite severity score from the multi-factor SeverityEngine */
  @Column({ default: 0 })
  severityScore: number;

  @Column({
    type: 'enum',
    enum: IncidentPriority,
    default: IncidentPriority.LOW,
  })
  severityLevel: IncidentPriority;

  /**
   * Array of human-readable strings explaining the severity score.
   * This is the "interpretability" feature — NOT a black box.
   * Example: ["Large visible flame region (18.3% of frame)",
   *           "Fire area growing at +2.4% per sample (INCREASING)"]
   */
  @Column('jsonb', { nullable: true, default: [] })
  severityReasons: string[];

  // ── Response Priority ────────────────────────────────────────────────────

  @Column({
    type: 'enum',
    enum: IncidentPriority,
    default: IncidentPriority.LOW,
  })
  priority: IncidentPriority;

  // ── Incident Lifecycle Status ─────────────────────────────────────────────

  @Column({
    type: 'enum',
    enum: AiIncidentStatus,
    default: AiIncidentStatus.UNVERIFIED,
  })
  status: AiIncidentStatus;

  // ── Human Verification (set by BFP_STAFF/ADMIN) ──────────────────────────

  /** ID of the user who acknowledged this incident */
  @Column({ nullable: true })
  acknowledgedById: number;

  @Column({ nullable: true })
  acknowledgedByName: string;

  @Column({ type: 'timestamp', nullable: true })
  acknowledgedAt: Date;

  /** ID of the user who set the final verification status */
  @Column({ nullable: true })
  verifiedById: number;

  @Column({ nullable: true })
  verifiedByName: string;

  @Column({ type: 'timestamp', nullable: true })
  verifiedAt: Date;

  @Column({ type: 'timestamp', nullable: true })
  resolvedAt: Date;

  // ── Multi-Camera Correlation ──────────────────────────────────────────────

  /**
   * If this incident was correlated with another camera's incident,
   * this field holds the UUID of the "primary" incident.
   */
  @Column({ nullable: true })
  correlatedIncidentId: string;

  /** Number of cameras that have detected this event */
  @Column({ default: 1 })
  cameraCount: number;

  // ── Timestamps ───────────────────────────────────────────────────────────

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
